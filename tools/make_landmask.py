#!/usr/bin/env python3
"""Build js/landmask.js: a 1-degree land/sea bitmap (360 x 180, 1 bit per cell, base64) from the
public-domain Natural Earth 1:110m land polygons. Used for real continents in the Schumann scene.
  curl -sO https://raw.githubusercontent.com/nvkelso/natural-earth-vector/master/geojson/ne_110m_land.geojson
  python3 tools/make_landmask.py ne_110m_land.geojson
"""
import base64, json, os, sys
from PIL import Image, ImageDraw
src = sys.argv[1] if len(sys.argv) > 1 else "ne_110m_land.geojson"
W, H, S = 360, 180, 4  # draw at 4x and downsample (cell = land if >= 35% covered)
img = Image.new("L", (W * S, H * S), 0); d = ImageDraw.Draw(img)
xy = lambda lon, lat: ((lon + 180) * S, (90 - lat) * S)
for f in json.load(open(src))["features"]:
    g = f["geometry"]; polys = g["coordinates"] if g["type"] == "MultiPolygon" else [g["coordinates"]]
    for poly in polys:
        d.polygon([xy(*p[:2]) for p in poly[0]], fill=255)
        for hole in poly[1:]: d.polygon([xy(*p[:2]) for p in hole], fill=0)
small = img.resize((W, H), Image.BOX)
bits = bytearray(W * H // 8)
for y in range(H):
    for x in range(W):
        if small.getpixel((x, y)) >= 90: i = y * W + x; bits[i >> 3] |= 1 << (i & 7)
out = os.path.join(os.path.dirname(os.path.dirname(os.path.abspath(__file__))), "js", "landmask.js")
open(out, "w").write("// 1-degree land mask, row 0 = 89.5N, column 0 = 179.5W. From Natural Earth 1:110m land (public domain).\n"
    "// Generated by tools/make_landmask.py; one bit per cell, LSB first.\n"
    f"export const LAND_W = {W}, LAND_H = {H};\nexport const LAND_B64 = '{base64.b64encode(bytes(bits)).decode()}';\n")
print("wrote", out, sum(bin(b).count('1') for b in bits), "land cells")
